interface Props {
  text: string
  /** Dot pitch in px; a glyph is 5 pitches wide and 7 tall. */
  pitch?: number
  color?: string
  /** Colour of the unlit dots; '' draws none. */
  off?: string
  className?: string
  style?: CSSProperties
}

export default function DotText({ text, pitch = 4, color = '#f4f4f0', off = 'rgba(255,255,255,0.05)', className, style }: Props) {
  const chars = text.toUpperCase().split('')
  const r = pitch * 0.36
  const dots: { x: number; y: number; on: boolean }[] = []
  let col = 0
  for (const ch of chars) {
    const g = G[ch] ?? G[' ']
    const w = g[0].length
    for (let row = 0; row < 7; row++) {
      for (let c = 0; c < w; c++) {
        dots.push({ x: col + c, y: row, on: g[row][c] === '#' })
      }
    }
    col += w + 1
  }
  const width = Math.max(1, (col - 1) * pitch)
  const height = 7 * pitch
  return (
    <svg
      className={className}
      style={style}
      width={width}
      height={height}
      viewBox={`0 0 ${width} ${height}`}
      shapeRendering="geometricPrecision"
      aria-label={text}
    >
      {off && dots.filter((d) => !d.on).map((d, i) => (
        <circle key={`o${i}`} cx={d.x * pitch + pitch / 2} cy={d.y * pitch + pitch / 2} r={r} fill={off} />
      ))}
      {dots.filter((d) => d.on).map((d, i) => (
        <circle key={`n${i}`} cx={d.x * pitch + pitch / 2} cy={d.y * pitch + pitch / 2} r={r} fill={color} />
      ))}
    </svg>
  )
}

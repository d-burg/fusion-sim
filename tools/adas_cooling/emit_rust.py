"""Emit a Rust table module from coronal.py outputs (lz_<el>.txt)."""
import sys, math
els = [('n', 'NITROGEN', 7, 'adf11 scd96/acd96/plt96/prb96 (ADAS "96" GCR project)'),
       ('ne', 'NEON', 10, 'adf11 scd96/acd96/plt96/prb96 (ADAS "96" GCR project)'),
       ('ar', 'ARGON', 18, 'adf11 scd89/acd89/plt89/prb89 (Abels-van Maanen 1985 data)')]
out = []
out.append('//! Coronal-equilibrium cooling curves and mean charge states for seeded\n'
           '//! impurities, derived from OpenADAS adf11 data (open.adas.ac.uk, the\n'
           '//! Atomic Data and Analysis Structure, H. P. Summers et al.) at an electron\n'
           '//! density of 1e20 m^-3: ionisation balance from scd/acd, radiated power from\n'
           '//! plt (line) and prb (recombination + bremsstrahlung). Generated by\n'
           '//! tools/adas_cooling/ (do not edit by hand). Values are coronal: in a cold,\n'
           '//! dense divertor with finite impurity residence time the low-Z species\n'
           '//! radiate more than this (non-coronal enhancement), which the detachment\n'
           '//! model accounts for separately through its own calibration.\n\n')
out.append('/// One row of a cooling table: (T_e [eV], L_z [W m^3], <Z>, <Z^2>).\n'
           'pub type CoolingRow = (f64, f64, f64, f64);\n\n')
for el, name, z, src in els:
    rows = []
    for line in open(f'lz_{el}.txt'):
        if line.startswith('#'):
            continue
        te, lz, zb, z2 = (float(x) for x in line.split())
        if 1.0 <= te <= 2.0e4:
            rows.append((te, lz, zb, z2))
    out.append(f'/// {name.title()} (Z = {z}), from {src}.\n')
    out.append(f'pub const {name}: &[CoolingRow] = &[\n')
    for te, lz, zb, z2 in rows:
        te_s = f'{te:.6g}'
        if '.' not in te_s and 'e' not in te_s:
            te_s += '.0'
        out.append(f'    ({te_s}, {lz:.4e}, {zb:.4f}, {z2:.4f}),\n')
    out.append('];\n\n')
sys.stdout.write(''.join(out))
